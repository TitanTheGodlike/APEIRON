function procAgg(layer) {
  const cnt = S.proc[layer], c = PROC_AGG[layer], iso = isolated(), up = S[UPG_KEY[layer]];
  if (c && c.cnt === cnt && c.S === S && c.uv === UPG_VER && c.iso === iso && c.up === up) return c.a;
  const a = { qmult: 0, res: 0, clock: 0, flick: 0, qexp: 0, shard: 0, ess: 0, idle: 0, pulse: 0, pulsecd: 0, lucky: 0, insight: 0, head: 0, surge: 0, fold: 0, tier: {}, thrift: {}, reson: {}, syn: [] };
  const list = S.forge[layer].filter(u => u.own);
  for (const u of KIND_UPG[layer]) if (layer === 's' ? hasS(u.id) : up[u.id]) list.push(u);
  for (const u of list) {
    switch (u.kind) {
      case 'tier': a.tier[u.tier] = (a.tier[u.tier] || 0) + u.v; break;
      case 'thrift': a.thrift[u.tier] = (a.thrift[u.tier] || 0) + L10(1 - u.v); break;
      case 'resonate': a.reson[u.tier] = (a.reson[u.tier] || 0) + 1; break;
      case 'synergy': a.syn.push(u); break;
      case 'pulsecd': case 'fold': a[u.kind] += L10(1 - u.v); break;
      case 'windfall': case 'hoard': break; // one-time gifts, paid out when bought
      default: if (u.kind in a) a[u.kind] += u.v;
    }
  }
  PROC_AGG[layer] = { cnt, a, S, uv: UPG_VER, iso, up };
  return a;
}
