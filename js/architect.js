  u.own = true; S.proc[layer]++; S.secret.ideasAsc++;
  if (u.kind === 'windfall') { const p = qpsLog(); if (p > -Infinity) { u.gave = p + L10(u.v); S.q = S.q.add(D.fromLog(u.gave)); capQ(); } }
