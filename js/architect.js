function forgeValue(layer, kind, n) {
  const big = (a, b, c) => layer === 'q' ? a : layer === 's' ? b : c;
  switch (kind) {
    case 'qmult': return big(0.5 + 0.01 * n, 1 + 0.06 * n, 5 + 0.2 * n);
    case 'tier': return big(0.6 + 0.0125 * n, 1.2 + 0.06 * n, 5 + 0.2 * n);
    case 'idle': return big(0.8 + 0.015 * n, 1.5 + 0.07 * n, 6 + 0.25 * n);
    case 'pulse': return 0.5 + 0.025 * n;
    case 'res': return big(0.01, 0.02, 0.02);
    case 'clock': return big(0.001, 0.004, 0.004);
    case 'flick': return 0.25;
    case 'qexp': return big(0.0015, 0.005, 0.005);
    case 'shard': return big(0, L10(1.5), 1);
    case 'ess': return L10(1.5);
    case 'thrift': return big(0.12, 0.1, 0.15);   // price growth of one generator (or Clock Speed) −12%
    case 'synergy': return big(0.5, 0.8, 1.5);    // tier ×(1 + higher tier bought)^v
    case 'resonate': return 1;                    // resonates one purchase sooner
    case 'pulsecd': return 0.1;                   // Pulse recharges 10% faster
    case 'lucky': return 0.06;                    // chance of a Lucky Pulse
    case 'windfall': return 300 + 10 * n;         // seconds of production, paid out once
    case 'insight': return big(2, 0.3, 0.2);      // the Architect's other ideas cost less (log)
    case 'head': return big(0, 4, 8);             // Collapses start with more Quanta (log)
    case 'hoard': return 0.2;                     // share of Shards earned, paid out once
    case 'surge': return 5;                       // seconds
    case 'fold': return 0.1;                      // Time Fold recharges 10% faster
  }
  return 0;
}
