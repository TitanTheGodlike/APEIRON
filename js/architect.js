// The speech bubble: types the line out with little blips, holds it, then shows the next one (clicking skips)
const SAY = { q: [], busy: false, timer: 0, typing: false, full: '' };
function say(text) {
  if (S.settings.ui && !S.settings.ui.toasts) return;
  if (!tutorialDone()) return; // the tutorial is talking: the line stays in the Architect log only
  SAY.q.push(text); if (SAY.q.length > 6) SAY.q.splice(0, SAY.q.length - 6); // lines wait their turn; only a long backlog drops the oldest
  if (!SAY.busy) sayNext();
}
