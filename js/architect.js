function forgeNew(layer) {
  const list = S.forge[layer], n = list.length, style = playStyle();
  const w = Object.assign({}, FORGE_KINDS[layer]);
  if (style === 'active' && layer === 'q') { w.pulse = 3; w.pulsecd *= 2; w.lucky *= 2; }
  if (style === 'idle') w.idle = 3;
  // some ideas only make sense once their system exists, and stop once they are maxed out
  const top = highestTier();
  const resTiers = []; for (let i = 0; i <= top; i++) if (resStep(i) > RES_MIN) resTiers.push(i);
  if (!resTiers.length) w.resonate = 0;
  if (top < 1) w.synergy = 0;
  if (Math.pow(10, procSum('pulsecd')) <= CD_FLOOR + 1e-9) w.pulsecd = 0;
  if (procSum('lucky') >= LUCKY_MAX) w.lucky = 0;
  if (!S.sUpg.s25) w.surge = 0;
  if (!S.sUpg.s26 || Math.pow(10, procSum('fold')) <= CD_FLOOR + 1e-9) w.fold = 0;
  if (S.totalShards.log10() < 1) w.hoard = 0;
  if (headStartLog() >= HEAD_CAP) w.head = 0;
  const last = list.slice(-2).map(u => u.kind);
  if (last.length === 2 && last[0] === last[1]) w[last[0]] = 0;
  if (list.slice(-6).some(u => u.kind === 'qexp')) w.qexp = 0;
  let tot = 0; for (const k in w) tot += w[k];
  let r = Math.random() * tot, kind = 'qmult';
  for (const k in w) { if (!(w[k] > 0)) continue; r -= w[k]; if (r <= 0) { kind = k; break; } }
  let tier = null, src;
  if (kind === 'tier') tier = Math.random() < 0.5 ? top : favouriteTier();
  else if (kind === 'thrift') tier = Math.random() < 0.25 ? -1 : (Math.random() < 0.5 ? top : favouriteTier());
  else if (kind === 'resonate') tier = rnd(resTiers);
  else if (kind === 'synergy') { src = 1 + Math.floor(Math.random() * top); tier = Math.random() < 0.6 ? src - 1 : Math.floor(Math.random() * src); }
  const bits = NAME_BITS[kind];
  const name = kind === 'tier' || kind === 'resonate' ? genDef(tier).name + ' ' + rnd(bits[1])
    : kind === 'synergy' ? genDef(src).name + '–' + genDef(tier).name + ' ' + rnd(bits[1])
    : rnd(bits[0]) + ' ' + rnd(bits[1]);
  const reason = rnd((REASONS[kind] || REASONS.any)(tier, src));
  const u = { n, kind, v: forgeValue(layer, kind, n), tier, name, reason, own: false };
  if (src !== undefined) u.src = src;
  if (WEB_DEF[layer]) { u.branch = ARCH_BRANCH[layer](kind, tier); u.parent = pickParentWeb(layer, u.branch); }
  list.push(u);
  return u;
}
